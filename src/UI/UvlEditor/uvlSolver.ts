/** Solver engines exposed by the UVL editor. */
export type UvlSolverType = "sat" | "bdd";

export type UvlSolverStatus = "sat" | "unsat" | "unknown" | "error";

export type UvlSolverAnalysisResult = {
  solver: UvlSolverType;
  status: UvlSolverStatus;
  title: string;
  summary: string;
  details: string[];
  /** A satisfying feature assignment, when one was found. */
  model?: Record<string, boolean>;
  /** Number of satisfying feature assignments for BDD analysis. */
  modelCount?: number;
  featureCount?: number;
  clauseCount?: number;
  bddNodeCount?: number;
  elapsedMs?: number;
};

export type UvlSolverOptions = {
  /** Maximum wall-clock time for one analysis. */
  maxMillis?: number;
  /** Maximum DPLL decisions. */
  maxDecisions?: number;
  /** Maximum SAT variables generated by the Tseitin encoding. */
  maxSatVariables?: number;
  /** Maximum generated SAT clauses. */
  maxSatClauses?: number;
  /** Maximum reduced BDD nodes. */
  maxBddNodes?: number;
};

type Formula =
  | { kind: "constant"; value: boolean }
  | { kind: "variable"; variable: number }
  | { kind: "not"; operand: Formula }
  | { kind: "and" | "or"; operands: Formula[] }
  | { kind: "cardinality"; variables: number[]; min: number; max: number; parent?: number };

type FeatureEntry = {
  feature: UvlFeature;
  variable: number;
  displayName: string;
};

type CompileContext = {
  featureByName: Map<string, FeatureEntry>;
  featureEntries: FeatureEntry[];
  unsupported: string[];
  unsupportedKeys: Set<string>;
};

type CompileResult = {
  formulas: Formula[];
  featureEntries: FeatureEntry[];
  unsupported: string[];
  topLevelConstraintCount: number;
};

type SatResult = {
  status: "sat" | "unsat" | "unknown";
  assignment?: Int8Array;
  decisions: number;
  propagations: number;
  conflicts: number;
  elapsedMs: number;
  reason?: string;
};

type BddResult = {
  status: "sat" | "unsat" | "unknown";
  root: number;
  model?: Record<string, boolean>;
  modelCount?: number;
  nodeCount: number;
  elapsedMs: number;
  reason?: string;
};

